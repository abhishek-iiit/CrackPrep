type Topic = { title: string; slug: string; number: string; url?: string };

type ModuleDef = {
  id: string;
  slug: string;
  title: string;
  blurb: string;
  colorKey: string;
  topics: Topic[];
};

function modulesFile(modules: ModuleDef[], courseLabel: string): string {
  const records = modules
    .map(
      (mod) => `  {
    id: "${mod.id}",
    slug: "${mod.slug}",
    dir: "${mod.id}-${mod.slug}",
    title: ${JSON.stringify(mod.title)},
    blurb: ${JSON.stringify(mod.blurb)},
    colorKey: "${mod.colorKey}",
    topicCount: ${mod.topics.length},
  },`,
    )
    .join("\n");

  return `// GENERATED by scripts/generate-planned-courses.ts — re-run to refresh stubs.
// Planned course scaffold for ${courseLabel}. Not loaded by lib/content until live.
import type { ColorKey } from "@/lib/design/modules";

export type ModuleRecord = {
  id: string;
  slug: string;
  dir: string;
  title: string;
  blurb: string;
  colorKey: ColorKey;
  topicCount: number;
};

export const modules: ModuleRecord[] = [
${records}
];
`;
}

function writeCourse(courseSlug: string, modules: ModuleDef[]): { created: number; kept: number } {
  const courseDir = join(ROOT, "content", courseSlug);
  mkdirSync(courseDir, { recursive: true });
  writeFileSync(join(courseDir, "modules.ts"), modulesFile(modules, courseSlug), "utf8");

  let created = 0;
  let kept = 0;
  for (const mod of modules) {
    const dir = join(courseDir, `${mod.id}-${mod.slug}`);
    mkdirSync(dir, { recursive: true });
    for (const topic of mod.topics) {
      const file = join(dir, `${topic.slug}.mdx`);
      if (existsSync(file)) {
        kept++;
        continue;
      }
      const summary = topic.url
        ? `${topic.title} — ${topic.url}`
        : undefined;
      writeFileSync(file, stub(topic.title, topic.number, summary), "utf8");
      created++;
    }
  }
  return { created, kept };
}

function topicsFrom(
  titles: string[],
  moduleId: string,
  urls?: (string | undefined)[],
): Topic[] {
  return titles.map((title, i) => {
    const n = String(i + 1).padStart(2, "0");
    return {
      title,
      slug: slugify(title),
      number: `${moduleId}.${n}`,
      url: urls?.[i],
    };
  });
}

function lc(slug: string): string {
  return `https://leetcode.com/problems/${slug}/`;
}

