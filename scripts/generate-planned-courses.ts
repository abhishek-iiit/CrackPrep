function writeSyllabusDp(modules: ModuleDef[]): void {
  const lines = [
    "# Design Patterns syllabus",
    "",
    "Classic Gang of Four patterns, grouped for the planned `design-patterns` course.",
    "",
  ];
  for (const mod of modules) {
    lines.push(`## ${mod.id} ${mod.title}`);
    lines.push("");
    lines.push(mod.blurb);
    lines.push("");
    for (const t of mod.topics) {
      lines.push(`- ${t.number} ${t.title}`);
    }
    lines.push("");
  }
  writeFileSync(join(ROOT, "DesignPatternsSyllabus.md"), lines.join("\n"), "utf8");
}

function writeSyllabusLc(modules: ModuleDef[]): void {
  const lines = [
    "# LeetCode roadmap syllabus",
    "",
    "Curated 150 problems in three phases (50 each), scaffold for the planned `leetcode` course.",
    "Aligned with the Ultimate LeetCode Roadmap structure; diff titles/URLs against the Medium source when updating.",
    "",
    "Source article: https://medium.com/@abhishek-iiit/ultimate-leetcode-roadmap-curated-150-questions-to-crack-0768c78b942b",
    "",
  ];
  for (const mod of modules) {
    lines.push(`## ${mod.id} ${mod.title}`);
    lines.push("");
    lines.push(mod.blurb);
    lines.push("");
    for (const t of mod.topics) {
      lines.push(`- ${t.number} ${t.title}${t.url ? ` — ${t.url}` : ""}`);
    }
    lines.push("");
  }
  writeFileSync(join(ROOT, "LeetCodeSyllabus.md"), lines.join("\n"), "utf8");
}

