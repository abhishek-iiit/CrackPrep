function phaseModule(
  id: string,
  slug: string,
  title: string,
  blurb: string,
  colorKey: string,
  items: LCItem[],
): ModuleDef {
  if (items.length !== 50) {
    throw new Error(`${title} must have 50 problems, got ${items.length}`);
  }
  return {
    id,
    slug,
    title,
    blurb,
    colorKey,
    topics: items.map((item, i) => {
      const n = String(i + 1).padStart(2, "0");
      return {
        title: item.title,
        slug: slugify(item.title),
        number: `${id}.${n}`,
        url: lc(item.slug),
      };
    }),
  };
}

